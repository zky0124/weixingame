const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'../游戏策划/科技树表格'),M=require(path.join(root,'科技树模型.js'));
const context={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'科技树初始数据.js'),'utf8'),context);
const seed=M.validate(JSON.parse(JSON.stringify(context.window.TECH_TREE_SEED)));
assert.equal(seed.nodes.length,19);assert(seed.nodes.some(n=>n.name==='高效研究'));assert(seed.nodes.some(n=>n.name==='法师塔'));
let {doc,id}=M.add(seed,'T001');doc=M.update(doc,id,{name:'护卫精进',points:0,coins:null,effect:'护甲+1'});
assert.equal(doc.nodes.find(n=>n.id===id).points,0);assert.equal(doc.nodes.find(n=>n.id===id).coins,null);
assert.equal(seed.nodes.length,19,'不可意外修改原始模板');
const extra=M.add(doc,id);assert.throws(()=>M.remove(extra.doc,id),/依赖/);
assert.throws(()=>M.update(extra.doc,'T001',{parent:extra.id}),/循环/);
assert.throws(()=>M.update(extra.doc,'T002',{requires:[extra.id]}).nodes&&M.update(M.update(extra.doc,'T002',{requires:[extra.id]}),extra.id,{requires:['T002']}),/循环/);
assert.throws(()=>M.update(doc,id,{requires:['不存在']}),/不存在/);
assert.throws(()=>M.update(doc,id,{points:-1}),/非负/);
assert.throws(()=>M.update(doc,id,{level:1.2}),/非负|整数/);
const damaged=M.clone(seed);damaged.nodes[1].id=damaged.nodes[2].id;assert.throws(()=>M.validate(damaged),/重复/);
assert.throws(()=>M.remove(seed,'ROOT'),/中心/);
const laid=M.layout(doc);assert.equal(laid.nodes.find(n=>n.id===id).effect,'护甲+1');assert.equal(laid.nodes.find(n=>n.id===id).points,0);
const restored=M.validate(JSON.parse(JSON.stringify(laid)));assert.deepEqual(restored,laid);
const removed=M.remove(doc,id);assert.equal(removed.nodes.length,seed.nodes.length);
const joined=M.connect(extra.doc,'T002',extra.id);
assert(joined.nodes.find(n=>n.id===extra.id).requires.includes('T002'),'可合并法师与战士两条路线');
assert.equal(joined.nodes.find(n=>n.id===extra.id).parent,id,'跨路线连线不改变主路径');
assert.throws(()=>M.connect(joined,extra.id,'T002'),/循环/);
assert.equal(M.connect(joined,'T002',extra.id).nodes.find(n=>n.id===extra.id).requires.length,1,'重复连线不叠加');
assert(!M.disconnect(joined,'T002',extra.id).nodes.find(n=>n.id===extra.id).requires.length);
for(const file of ['科技树系统.js','科技树模型.js','科技树初始数据.js'])new vm.Script(fs.readFileSync(path.join(root,file),'utf8'),{filename:file});
console.log('科技规划器验证通过：新增/删除、保存原值、空白与0、前置循环、错误导入、布局保留内容与JSON往返。');
