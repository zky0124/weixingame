const assert=require('node:assert/strict'),path=require('node:path');
const output=path.resolve(process.argv[2]);
const R=require(path.join(output,'城市/ResearchEconomy.js'));
const {BattleModel}=require(path.join(output,'战斗/BattleModel.js'));
const s=R.newResearchState();assert.equal(R.tickResearch(s,60),0,'没有建塔不计被动');s.towerBuilt=true;
assert.equal(R.tickResearch(s,29.5),0);assert.equal(R.tickResearch(s,.5),1);assert.equal(s.timer,0);
assert.equal(R.researchWildWave(s,'wild-1'),1);assert.equal(R.researchWildWave(s,'wild-1'),0,'整波只发一次');
assert.equal(R.researchRound(s,1),5);assert.equal(R.researchRound(s,1),0);assert.equal(R.researchRound(s,3),0,'不能跳号刷点');
s.outputBonus=1;assert.equal(R.tickResearch(s,60),4,'每次30秒均受加成，不是整批只加1');
assert.equal(R.researchWildWave(s,'wild-2'),2);assert.equal(R.researchRound(s,2),6);
assert.equal(R.researchSettlementSupport(s),21);assert.equal(R.researchSettlementSupport(s),0);
assert(R.validResearchState(s));const copy=JSON.parse(JSON.stringify(s));assert(R.validResearchState(copy));assert.equal(R.researchWildWave(copy,'wild-2'),0);
const model=new BattleModel();assert.equal(model.armyCapacity,3);model.state.coins=10;assert(!model.recruit());
