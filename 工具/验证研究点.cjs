model.state.phase='defeat';assert(model.retry());assert.equal(model.research.points,0);assert(model.startRound());assert.equal(model.research.points,5,'整次回滚后重试不累积重复奖励');
const legacy=model.save();delete legacy.state.research;delete legacy.checkpoint.research;
const loaded=BattleModel.load(legacy);assert(loaded);assert.equal(loaded.research.points,5);assert.equal(BattleModel.load(loaded.save()).research.points,5,'迁移不重复补发');
loaded.research.towerBuilt=true;loaded.tickProduction(30);assert.equal(loaded.research.points,6);
loaded.research.outputBonus=1;loaded.tickProduction(30);assert.equal(loaded.research.points,8);
loaded.state.phase='defeat';loaded.tickProduction(30);assert.equal(loaded.research.points,8);
const bad=loaded.save();bad.state.research.outputBonus=-1;assert.equal(BattleModel.load(bad),null);
console.log('研究点验证通过：30秒、整波野怪、推进回合、全部产出+1、一次性支援、重复事件、重试回滚、存档迁移与坏档检查。');
