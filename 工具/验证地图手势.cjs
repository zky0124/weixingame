const assert = require('node:assert/strict');
const path = require('node:path');
const { MapViewport } = require(path.resolve(process.argv[2], '界面/MapViewport.js'));
const near = (a,b) => assert(Math.abs(a-b)<1e-8, `${a} != ${b}`);
const map = new MapViewport({x:600,y:280});
const anchor = {x:100,y:30};
const world = map.toWorld(anchor);
map.zoomAt(anchor, 2);
near(map.toWorld(anchor).x,world.x); near(map.toWorld(anchor).y,world.y);
map.zoomAt(anchor, 100); near(map.zoom,2.5);
map.zoomAt(anchor, 0.001); near(map.zoom,0.65);
map.reset();
map.begin(1,{x:-100,y:0}); map.begin(2,{x:100,y:0});
map.move(1,{x:-150,y:0}); map.move(2,{x:150,y:0});
near(map.zoom,1.5); near(map.x,0); near(map.y,0);
// 双指中心整体移动，不改变间距，完成后净效果仅平移。
map.move(1,{x:-130,y:20}); map.move(2,{x:170,y:20});
near(map.zoom,1.5); near(map.x,20); near(map.y,20);
assert.equal(map.end(2),false);
map.move(1,{x:-110,y:30}); near(map.x,40); near(map.y,30);
assert.equal(map.end(1),false,'双指松开后不能触发点选');
map.begin(3,{x:0,y:0}); map.move(3,{x:3,y:2}); assert.equal(map.end(3),true);
map.begin(4,{x:0,y:0}); map.move(4,{x:100,y:50}); assert.equal(map.end(4),false);
map.begin(5,{x:0,y:0}); assert.equal(map.end(5,true),false);
map.begin(6,{x:0,y:0}); map.cancel(); assert.equal(map.end(6),false);
map.begin(7,{x:0,y:0}); map.move(7,{x:99999,y:99999});
assert(Math.abs(map.x)<=600*map.zoom && Math.abs(map.y)<=280*map.zoom);
map.reset(); near(map.zoom,1); near(map.x,0); near(map.y,0);
const city = new MapViewport({x:450,y:200}); city.zoomAt({x:0,y:0},2);
near(map.zoom,1); near(city.zoom,2);
console.log('地图手势验证通过：锚点缩放、上下限、双指缩放/平移、松指续拖、防误点、取消、边界及独立视角。');
